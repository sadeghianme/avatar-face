// The widget's types for the API answers it reads, generated from the
// committed OpenAPI document: frontend/src/lib/api-schema.json, which
// backend/scripts/export_openapi.py writes and CI holds to the backend
// (the backend job). One generator for the schema, one contract for the
// dashboard (openapi-typescript) and the widget (this script).
//
//   node scripts/gen-api-types.mjs           # write src/api-types.ts
//   node scripts/gen-api-types.mjs --check   # exit 1 when it is stale
//
// Small on purpose: only the answers the widget reads (ROOTS) and what they
// refer to, as plain interfaces, so the widget does not carry the whole API's
// types. Covers the JSON Schema Pydantic emits for them; anything else is an
// error here rather than a wrong type.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA = resolve(ROOT, "../frontend/src/lib/api-schema.json");
const OUT = resolve(ROOT, "src/api-types.ts");

/** The answers the widget reads: GET /embed/v1/avatars/{id},
 *  POST /embed/v1/synthesize and POST /embed/v1/cues. */
const ROOTS = ["EmbedAvatarOut", "SynthesizeResponse", "CueResponse"];

const PREFIX = "#/components/schemas/";

function refName(ref) {
  if (!ref.startsWith(PREFIX)) throw new Error(`unsupported $ref ${ref}`);
  return ref.slice(PREFIX.length);
}

/** Every schema `roots` reach through $ref, sorted by name. */
function reachable(schemas, roots) {
  const seen = new Set();
  const visit = (node) => {
    if (Array.isArray(node)) return node.forEach(visit);
    if (!node || typeof node !== "object") return;
    if (typeof node.$ref === "string") {
      const name = refName(node.$ref);
      if (!seen.has(name)) {
        if (!schemas[name]) throw new Error(`no schema ${name}`);
        seen.add(name);
        visit(schemas[name]);
      }
    }
    Object.values(node).forEach(visit);
  };
  roots.forEach((name) => visit({ $ref: PREFIX + name }));
  return [...seen].sort();
}

function union(types) {
  return [...new Set(types)].join(" | ");
}

/** The TypeScript for one JSON Schema node. */
function tsType(schema) {
  if (schema.$ref) return refName(schema.$ref);
  if ("const" in schema) return JSON.stringify(schema.const);
  if (schema.enum) return union(schema.enum.map((value) => JSON.stringify(value)));
  if (schema.anyOf) return union(schema.anyOf.map(tsType));
  if (schema.oneOf) return union(schema.oneOf.map(tsType));
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      const item = tsType(schema.items);
      return item.includes(" ") ? `(${item})[]` : `${item}[]`;
    }
    case "object":
      if (schema.properties) return `{ ${members(schema).join(" ")} }`;
      if (schema.additionalProperties && schema.additionalProperties !== true) {
        return `Record<string, ${tsType(schema.additionalProperties)}>`;
      }
      return "Record<string, unknown>";
    default:
      throw new Error(`unsupported schema ${JSON.stringify(schema)}`);
  }
}

function doc(text) {
  if (!text) return "";
  const lines = text.replaceAll("*/", "*\\/").split("\n");
  return `/**\n${lines.map((line) => ` * ${line}`.trimEnd()).join("\n")}\n */\n`;
}

function members(schema) {
  const required = new Set(schema.required ?? []);
  return Object.entries(schema.properties).map(([name, property]) => {
    const optional = required.has(name) ? "" : "?";
    return `${doc(property.description)}${name}${optional}: ${tsType(property)};`;
  });
}

function declaration(name, schema) {
  const comment = doc(schema.description);
  if (schema.type === "object" && schema.properties) {
    return `${comment}export interface ${name} {\n${members(schema).join("\n")}\n}\n`;
  }
  return `${comment}export type ${name} = ${tsType(schema)};\n`;
}

async function generate() {
  const schemas = JSON.parse(readFileSync(SCHEMA, "utf8")).components.schemas;
  const header =
    "// GENERATED by scripts/gen-api-types.mjs from the committed OpenAPI document\n" +
    "// (frontend/src/lib/api-schema.json). Do not edit: change the backend's\n" +
    "// schemas, export the document (backend/scripts/export_openapi.py), and\n" +
    "// run `npm run gen:api`.\n\n";
  const body = reachable(schemas, ROOTS)
    .map((name) => declaration(name, schemas[name]))
    .join("\n");
  const options = await prettier.resolveConfig(OUT);
  return prettier.format(header + body, { ...options, parser: "typescript" });
}

const text = await generate();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // Missing counts as stale.
  }
  if (current !== text) {
    console.error("src/api-types.ts is stale: run `npm run gen:api` and commit it.");
    process.exit(1);
  }
  console.log("src/api-types.ts matches the committed OpenAPI document");
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
